import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
const root = resolve(import.meta.dirname, '..');
const directory = mkdtempSync(join(tmpdir(), 'healing-consumer-'));
const env = Object.fromEntries(['PATH', 'HOME', 'TMPDIR', 'CI', 'PLAYWRIGHT_BROWSERS_PATH', 'npm_config_cache'].filter(k => process.env[k]).map(k => [k, process.env[k]]));
try {
  const packed = JSON.parse(execFileSync('npm', ['pack', '--json', '--ignore-scripts', '--pack-destination', directory], { cwd: root, env, encoding: 'utf8' }))[0];
  const allowed = /^(dist\/[a-z-]+\.(?:js|d\.ts)|README\.md|LICENSE|THIRD_PARTY_NOTICES\.md|LICENSES\/OpenSpec-MIT\.txt|package\.json|docs\/(?:integration|playwright)\.md|docs\/implementation\/(?:component-inventory|thesis-method-alignment)\.md)$/;
  for (const file of packed.files) assert.match(file.path, allowed, `Unexpected package asset: ${file.path}`);
  for (const required of ['LICENSE', 'THIRD_PARTY_NOTICES.md', 'LICENSES/OpenSpec-MIT.txt']) assert(packed.files.some(f => f.path === required), `Missing distribution notice: ${required}`);
  assert(packed.files.some(f => f.path === 'dist/index.js'));
  assert(packed.files.some(f => f.path === 'docs/integration.md'));
  assert(packed.files.some(f => f.path === 'docs/implementation/thesis-method-alignment.md'));
  const consumer = join(directory, 'consumer'); mkdirSync(consumer);
  writeFileSync(join(consumer, 'package.json'), JSON.stringify({ name: 'independent-consumer-check', version: '1.0.0', private: true, type: 'module' }));
  execFileSync('npm', ['install', '--prefer-offline', '--ignore-scripts', '--no-audit', '--no-fund', '--package-lock=false', join(directory, packed.filename), 'playwright@1.62.1'], { cwd: consumer, env, stdio: 'pipe' });
  writeFileSync(join(consumer, 'smoke.mjs'), `import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import * as api from 'self-healing-tool';
import {mkdtemp,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
assert.deepEqual(Object.keys(api).sort(), ['ConfigurationError','DEFAULT_CONFIG','HealingFailure','ProviderError','configFromEnv','createHealingSession','createOpenAIProvider','createBudgetedOpenAIProvider','createLiveBudget','readLiveBudget','serializeRequest','renderReport','reportView','summarize','validateConfig','writeReport','loadTargetSpec','validateTargetContract'].sort());
const browser = await chromium.launch();
try {
 const page = await browser.newPage();
 await page.setContent('<label>Display name<input id="current"></label>');
 const session = api.createHealingSession(page, { config: { actionTimeoutMs: 1000 } });
 await session.fill('#current', 'normal', {description:'Display name'});
 await session.fill('#old', 'recovered', {description:'Display name'});
 assert.equal(await page.locator('#current').inputValue(), 'recovered');
 assert.equal(session.snapshot().events[1].actionExecuted, true);
 assert.equal(session.snapshot().provider, 'none');
 const contract=api.validateTargetContract({schemaVersion:1,requirementId:'CONSUMER-01',revision:'v1',intent:'Edit display name',action:'fill',status:'active',allOf:[{sources:['nearestLabel'],anyOf:['Display name']}]});
 const guarded=api.createHealingSession(page,{config:{actionTimeoutMs:1000},targetSpec:{mode:'enforce',contract,expectedRevision:'v1'}});
 await guarded.fill('#previous', 'guarded',{description:'Display name'});
 assert.equal(await page.locator('#current').inputValue(),'guarded');
 assert.equal(guarded.snapshot().events[0].targetSpec.decision.outcome,'accepted');
 assert.equal(typeof api.loadTargetSpec,'function');
 const config=api.validateConfig({mode:'full',actionTimeoutMs:100});
 const provider={kind:'offline',async select(context,signal,audit){audit?.request(api.serializeRequest(context,config));return {output:JSON.stringify({selector:'#current'}),usage:null};}};
 const audited=api.createHealingSession(page,{config,provider,audit:true});
 await audited.fill('#outdated','new value',{description:'Display name'});
 const output=await api.writeReport(audited.snapshot(),{directory:await mkdtemp(join(tmpdir(),'installed-report-')),audit:audited.audit()});
 const summary=await readFile(join(output,'report.json'),'utf8');assert(!summary.includes('messages'));
 await page.goto(pathToFileURL(join(output,'report.html')).href);
 await page.getByRole('button',{name:'Inspect action'}).click();await page.locator('#stage-ai').click();
 assert((await page.locator('.stage-panel').innerText()).includes('SHA-256 matches'));
 await page.locator('#report-language').selectOption('id');assert.equal(await page.locator('#stage-title').innerText(),'Input dan jawaban AI');
 assert.equal(await page.locator('.method-switch').isVisible(),false);
 console.log('Packaged local audit: recorded request/output, English/Indonesian, no study controls passed');
 console.log('Clean tarball consumer: import, normal fill, ranker recovery and target-contract gate passed');
} finally { await browser.close(); }
`);
  execFileSync(process.execPath, ['smoke.mjs'], { cwd: consumer, env, stdio: 'inherit' });
  const packageJson = JSON.parse(readFileSync(join(consumer, 'node_modules/self-healing-tool/package.json'), 'utf8'));
  assert.equal(packageJson.peerDependencies.playwright, '1.62.1');
  assert.equal(packageJson.license, 'MIT');
  assert.equal(packageJson.private, true); // GitHub source release does not publish to npm.
  assert.equal(packageJson.version, JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version);
  assert.match(readFileSync(join(consumer, 'node_modules/self-healing-tool/LICENSE'), 'utf8'), /Copyright \(c\) 2026 Wildan Syukri Niam/);
  console.log(JSON.stringify({ node: process.version, playwright: '1.62.1', packageFiles: packed.files.map(f => f.path), result: 'pass' }));
} finally { rmSync(directory, { recursive: true, force: true }); }
