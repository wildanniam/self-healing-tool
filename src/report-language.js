/** Translate authored UI strings only. Evidence interpolations are never translated. */
export function languageClient(dictionary, initial = 'en') {
  let language = initial === 'id' ? 'id' : 'en';
  const reverse = Object.fromEntries(Object.entries(dictionary).map(([id, en]) => [en, id]));
  const listeners = [], bindings = [];
  function word(value) {
    const key = dictionary[value] !== undefined ? value : reverse[value];
    return key === undefined ? value : language === 'en' ? dictionary[key] : key;
  }
  function fragment(value) {
    return value.replace(/(^|>)([^<>]*)(?=<|$)/g, (_, lead, text) => lead + text.replace(/^(\s*)(.*?)(\s*)$/s, (_, a, b, c) => a + word(b) + c))
      .replace(/(aria-label|placeholder)="([^"]*)"/g, (_, key, value) => `${key}="${word(value)}"`);
  }
  function text(value) { return typeof value === 'string' ? (value.includes('<') ? fragment(value) : value.replace(/^(\s*)(.*?)(\s*)$/s, (_, a, b, c) => a + word(b) + c)) : value; }
  function html(parts, ...values) { return parts.reduce((out, part, i) => out + fragment(part) + (i < values.length ? values[i] : ''), ''); }
  function update() {
    document.documentElement.lang = language;
    const select = document.getElementById('report-language');
    if (select) select.value = language;
    for (const [node, attribute, original] of bindings) {
      if (attribute) node.setAttribute(attribute, text(original)); else node.nodeValue = text(original);
    }
  }
  function bindStatic(root) {
    // Call once on the authored shell, before inserting any recorded evidence.
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (node.parentElement?.closest('script,style,pre,code,[data-evidence]')) continue;
      if (dictionary[node.nodeValue.trim()] !== undefined || reverse[node.nodeValue.trim()] !== undefined) bindings.push([node, null, node.nodeValue]);
    }
    root.querySelectorAll('[aria-label],[placeholder]').forEach(node => {
      for (const attr of ['aria-label','placeholder']) { const value = node.getAttribute(attr); if (dictionary[value] !== undefined) bindings.push([node, attr, value]); }
    });
    update();
  }
  const select = document.getElementById('report-language');
  if (select) select.addEventListener('change', () => { language = select.value === 'id' ? 'id' : 'en'; update(); for (const callback of listeners) callback(); });
  update();
  return { text, html, bindStatic, subscribe(callback) { listeners.push(callback); }, get current() { return language; } };
}

